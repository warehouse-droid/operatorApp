import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {chromium,expect} from '@playwright/test';
import {app} from '../../../src/server.js';
import {config} from '../../../src/config.js';
import {query,closeDb} from '../../../src/db.js';
import {updateOperatorPassword,loginOperator} from '../../../src/auth-repository.js';
import {finalCollectionFixture,completeRentalPart} from '../support/bin-final-collection-fixtures.js';
import {storedPlan} from '../support/bin-planning-fixtures.js';
import {withBrowserCoverageSources} from '../support/browser-source-coverage.js';
after(closeDb);
test('final collection browser: visible red hold prevents dragging, preserves editing, and clears after all work completes',{timeout:90000},async()=>{
  const f=await finalCollectionFixture();
  await updateOperatorPassword(f.actor.operatorId,'collection-hold-browser-password');
  const token=(await loginOperator(f.actor.operatorId,'collection-hold-browser-password')).token;
  config.mbt.enabled=true;config.mbtPhase3.binDispatchEnabled=true;config.dispatch.driverOrientedPlanning=true;
  await query("UPDATE mbt_feature_flags SET enabled=true WHERE flag_key IN ('mbt_enabled','mbt_bin_dispatch')");
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});let browser;
  try {
    browser=await chromium.launch({headless:true,executablePath:'/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-linux64/chrome-headless-shell',args:['--no-sandbox','--disable-dev-shm-usage']});
    const context=await browser.newContext({viewport:{width:1500,height:1000}});context.setDefaultTimeout(10000);
    await context.addInitScript(({token,f})=>{
      localStorage.setItem('mbbs.staff.token',token);localStorage.setItem('mbbs.dispatch.planDate',f.planDate);
      sessionStorage.setItem('mbbs.dispatch.sessionId',f.editLease.sessionId);
      sessionStorage.setItem('mbbs.dispatch.editLease.v1',JSON.stringify({planDate:f.planDate,sessionId:f.editLease.sessionId,editLeaseToken:f.editLease.token,expiresAt:new Date(Date.now()+600000).toISOString()}));
    },{token,f});
    const page=await context.newPage(),errors=[];page.on('pageerror',error=>errors.push(error.message));
    await page.coverage.startJSCoverage({resetOnNavigation:false});
    await page.goto(`http://127.0.0.1:${server.address().port}/mbt/planning?planDate=${f.planDate}`);
    await expect.poll(()=>page.evaluate(()=>isDispatchPlanEditor())).toBe(true);
    await page.locator('.order-type-tabs').getByRole('button',{name:'Collection',exact:true}).click();
    const card=page.locator(`.order-card[data-order="${f.final.reference}"]`);
    const target=page.locator(`[data-load-card="${f.binLoadIds[0]}"] .stop-list`);
    await expect(card).toBeVisible();await expect(card).toHaveAttribute('draggable','false');
    await expect(card).toHaveCSS('background-color','rgb(255, 241, 242)');
    await expect(card).toContainText(f.delivery.reference);await expect(card).toContainText(f.collection.reference);
    await expect(card).toContainText('Waiting for');
    await card.dragTo(target);await expect(target.locator('.stop-card[data-stop]')).toHaveCount(0);
    const denied=await page.evaluate(({ref,load})=>({added:addOrderToLoad(ref,load),notice:routeNotice}),{ref:f.final.reference,load:f.binLoadIds[0]});
    assert.equal(denied.added,false);assert.match(denied.notice,/waiting.*complete/i);
    await card.click();await page.locator('[data-dispatch-order-actions]').getByRole('button',{name:'Plan collection',exact:true}).click();
    const dialog=page.getByRole('dialog',{name:`Plan ${f.final.reference}`});
    await expect(dialog.locator('[name="dumpSiteId"]')).toBeEnabled();
    await dialog.getByRole('button',{name:'Close workflow'}).click();
    const search=page.getByRole('textbox',{name:'Search orders',exact:true});
    await search.fill(f.final.reference);await expect(card).toHaveAttribute('draggable','false');
    await completeRentalPart(f,f.delivery);
    await search.fill('');await expect(card).toHaveAttribute('draggable','false');
    await expect(card.locator('[data-bin-collection-waiting]')).not.toContainText(f.delivery.reference);
    await completeRentalPart(f,f.collection);
    await search.fill(f.final.reference);
    await expect(card).toHaveAttribute('draggable','true');
    await expect(card.locator('[data-bin-collection-waiting]')).toHaveCount(0);
    await expect(card).not.toHaveCSS('background-color','rgb(255, 241, 242)');
    await card.dragTo(target);await expect(target.locator('.stop-card[data-stop]')).toHaveCount(3);
    const saved=await page.evaluate(async()=>{await saveCurrentPlanNow();return {dirty:localPlanDirty,notice:routeNotice};});
    assert.equal(saved.dirty,false,saved.notice);
    assert.ok((await storedPlan(f.planId)).trucks.flatMap(t=>t.loads.flatMap(l=>l.stops)).every(s=>s.mbt.visitId===f.finalId));
    assert.deepEqual(errors,[]);
    writeFileSync('test-artifacts/bin-final-collection-browser-v8.json',JSON.stringify(await withBrowserCoverageSources(page,await page.coverage.stopJSCoverage())));
  } finally {await browser?.close();await new Promise(resolve=>server.close(resolve));}
});
