import {withBrowserCoverageSources} from '../support/browser-source-coverage.js';
import test,{after} from 'node:test';
import assert from 'node:assert/strict';
import {writeFileSync} from 'node:fs';
import {chromium,expect} from '@playwright/test';
import {app} from '../../../src/server.js';
import {config} from '../../../src/config.js';
import {query,closeDb} from '../../../src/db.js';
import {updateOperatorPassword,loginOperator} from '../../../src/auth-repository.js';
import {createDispatchCustomOrder} from '../../../src/dispatch-custom-order-repository.js';
import {cargoFixture,yard150} from '../support/bin-cargo-fixtures.js';
import {getBinOrderWorkflow} from '../../../src/mbt/bin-order-workflow-service.js';
import {run,storedPlan} from '../support/bin-planning-fixtures.js';
import {getBinCargoOptions} from '../../../src/mbt/bin-cargo-service.js';
after(closeDb);
test('browser: Plan Delivery requires purchased mixed materials and saves manual or custom cargo',{timeout:120000},async()=>{
  const f=await cargoFixture({ordered:true}),manual=await cargoFixture();
  await query(`UPDATE mbt_service_visits SET service_snapshot=jsonb_set(service_snapshot,'{attachedAggregate,materials}',
    (service_snapshot->'attachedAggregate'->'materials') || $2::jsonb) WHERE service_visit_id=$1`,
  [f.frontVisitId,JSON.stringify([{itemCode:'SAND',displayName:'Sand',quantityMilliYards:1000,derivedWeightLbs:2000}])]);
  const order=await createDispatchCustomOrder({refNumber:'BROWSER-CARGO',pickupLocation:'10 Main St',dropoffLocation:'20 Main St',orderDetails:'Equipment',weightLbs:500},f.actor.operatorId);
  await updateOperatorPassword(f.actor.operatorId,'cargo-browser-password');
  const token=(await loginOperator(f.actor.operatorId,'cargo-browser-password')).token;
  config.mbt.enabled=true;config.mbtPhase3.binDispatchEnabled=true;config.dispatch.driverOrientedPlanning=true;
  await query("UPDATE mbt_feature_flags SET enabled=true WHERE flag_key IN ('mbt_enabled','mbt_bin_dispatch')");
  const server=await new Promise(resolve=>{const s=app.listen(0,'127.0.0.1',()=>resolve(s));});let browser;
  try {
    browser=await chromium.launch({headless:true,executablePath:'/ms-playwright/chromium_headless_shell-1234/chrome-headless-shell-linux64/chrome-headless-shell',args:['--no-sandbox','--disable-dev-shm-usage']});
    const context=await browser.newContext({viewport:{width:1500,height:1000}});context.setDefaultTimeout(10000);
    await context.addInitScript(({token,f})=>{
      localStorage.setItem('mbbs.staff.token',token);localStorage.setItem('mbbs.dispatch.planDate',f.planDate);
      sessionStorage.setItem('mbbs.dispatch.sessionId',f.editLease.sessionId);
      sessionStorage.setItem('mbbs.dispatch.editLease.v1',JSON.stringify({planDate:f.planDate,sessionId:f.editLease.sessionId,editLeaseToken:f.editLease.token,expiresAt:new Date(Date.now()+600000).toISOString()}));
    },{token,f});
    const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.coverage.startJSCoverage({resetOnNavigation:false});
    await page.goto(`http://127.0.0.1:${server.address().port}/mbt/planning?planDate=${f.planDate}`);
    await expect.poll(()=>page.evaluate(()=>isDispatchPlanEditor())).toBe(true);
    await page.evaluate(ref=>{selectedOrderId=ref;selectedOrderIds=new Set([ref]);render({save:false});},f.part.reference);
    const cargoUrl=`**/api/mbt/planning/workflows/${f.part.visitId}/cargo`;
    await page.route(cargoUrl,route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({error:'Cargo temporarily unavailable'})}));
    await page.locator('.selected-order-actions').getByRole('button',{name:'Plan delivery',exact:true}).click();
    await expect(page.locator('.bin-workflow-dialog [data-error]')).toContainText('Cargo temporarily unavailable');
    await expect(page.locator('.bin-workflow-dialog').getByRole('button',{name:'Save route',exact:true})).toBeDisabled();
    await page.locator('.bin-workflow-dialog').getByRole('button',{name:'Close workflow'}).click();
    await page.unroute(cargoUrl);
    await page.locator('.selected-order-actions').getByRole('button',{name:'Plan delivery',exact:true}).click();
    const dialog=page.locator('.bin-workflow-dialog');await expect(dialog.locator('[data-bin-cargo]')).toContainText('Gravel');
    await expect(dialog.locator('[data-bin-cargo]')).toContainText('Sand');
    await expect(dialog.locator('[name="cargoMode"]')).toHaveCount(0);
    await expect(dialog.locator('[data-cargo-required]')).toContainText('required');
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();
    await expect(dialog).toBeVisible();
    assert.equal((await getBinCargoOptions(f.part.visitId)).cargo.materials[0].pickup,null);
    await dialog.locator('[data-cargo-row="0"] [data-location="pickup"]').selectOption(yard150);
    await dialog.locator('[data-cargo-row="1"] [data-location="pickup"]').selectOption('address');
    await dialog.locator('[data-cargo-row="1"] [data-address="pickup"]').fill('30 Quarry Road');
    await dialog.locator('[data-cargo-row="1"] [data-location="dropoff"]').selectOption('address');
    await dialog.locator('[data-cargo-row="1"] [data-address="dropoff"]').fill('40 Delivery Road');
    await expect(dialog.locator('[data-cargo-preview]')).toContainText('Pick up Gravel');
    await expect(dialog.locator('[data-cargo-preview]')).toContainText('Drop off Sand');
    await expect(dialog.locator('input[type="datetime-local"]')).toHaveCount(0);
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();await expect(dialog).toHaveCount(0);
    const saved=await getBinCargoOptions(f.part.visitId);assert.equal(saved.cargo.materials.length,2);assert.equal(saved.cargo.materials[1].dropoff.address,'40 Delivery Road');
    // Details has no cargo editor; all route edits use Plan Delivery.
    await page.locator('.selected-order-actions').getByRole('button',{name:'Details',exact:true}).click();
    await expect(page.locator('.bin-visit-details [data-bin-cargo]')).toHaveCount(0);
    await page.locator('.bin-visit-details').getByRole('button',{name:'Close',exact:true}).click();
    const search=page.getByRole('textbox',{name:'Search orders',exact:true});
    await search.fill(manual.part.reference);
    await expect.poll(()=>page.evaluate(ref=>Boolean(orderById(ref)),manual.part.reference)).toBe(true);
    await page.evaluate(ref=>{selectedOrderId=ref;selectedOrderIds=new Set([ref]);render({save:false});},manual.part.reference);
    await page.locator('.selected-order-actions').getByRole('button',{name:'Plan delivery',exact:true}).click();
    await dialog.locator('[name="cargoMode"]').selectOption('one_off');
    await dialog.locator('[data-description]').fill('Tools');await dialog.locator('[data-weight]').fill('200');
    await dialog.locator('[data-location="pickup"]').selectOption('address');await dialog.locator('[data-address="pickup"]').fill('50 Main St');
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();await expect(dialog).toHaveCount(0);
    assert.equal((await getBinCargoOptions(manual.part.visitId)).cargo.custom.source,'one_off');
    await page.locator('.selected-order-actions').getByRole('button',{name:'Plan delivery',exact:true}).click();
    await dialog.locator('[name="cargoMode"]').selectOption('existing');await dialog.locator('[name="customOrderId"]').selectOption(order.id);
    await expect(dialog.locator('[data-cargo-preview]')).toContainText('BROWSER-CARGO');
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();await expect(dialog).toHaveCount(0);
    assert.equal((await getBinCargoOptions(manual.part.visitId)).cargo.custom.orderId,order.id);
    // A planned but unstarted delivery keeps its cargo editor in Plan Delivery.
    const part=(await getBinOrderWorkflow(f.frontVisitId)).parts[0];
    await run(f,'assign',{visitId:part.visitId,expectedVisitRevision:part.revision});
    await page.reload();await expect.poll(()=>page.evaluate(()=>isDispatchPlanEditor())).toBe(true);
    await page.getByRole('textbox',{name:'Search orders',exact:true}).fill(part.reference);
    await expect.poll(()=>page.evaluate(ref=>Boolean(orderById(ref)),part.reference)).toBe(true);
    await page.evaluate(ref=>{selectedOrderId=ref;selectedOrderIds=new Set([ref]);render({save:false});},part.reference);
    await page.locator('.selected-order-actions').getByRole('button',{name:'Plan delivery',exact:true}).click();
    await expect(dialog.locator('[name="deliveryAssetId"]')).toBeDisabled();
    await expect(dialog.locator('[data-location="pickup"]').first()).toBeEnabled();
    const revision=(await storedPlan(f.planId)).revision;
    await page.route(cargoUrl,route=>route.fulfill({status:409,contentType:'application/json',body:JSON.stringify({error:'Route save interrupted; retry'})}));
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();
    await expect(dialog.locator('[data-error]')).toContainText('Route save interrupted; retry');
    assert.equal((await storedPlan(f.planId)).revision,revision);
    await expect(dialog).toContainText('Sand');
    await page.unroute(cargoUrl);
    await dialog.getByRole('button',{name:'Save route',exact:true}).click();await expect(dialog).toHaveCount(0);
    assert.ok((await storedPlan(f.planId)).revision>revision);
    assert.deepEqual((await getBinCargoOptions(part.visitId)).cargo.materials.map(m=>m.description),['Gravel','Sand']);
    assert.deepEqual(errors,[]);
    writeFileSync('test-artifacts/bin-cargo-browser-v8.json',JSON.stringify(await withBrowserCoverageSources(page,await page.coverage.stopJSCoverage())));
  } finally {await browser?.close();await new Promise(resolve=>server.close(resolve));}
});
