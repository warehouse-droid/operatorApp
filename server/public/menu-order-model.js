function invalid(message) {
  const error = new Error(message);
  error.status = 400;
  return error;
}

export function normalizeMenuOrders(input) {
  if (!input || typeof input !== 'object' || Array.isArray(input)) {
    throw invalid('Menu orders must be an object.');
  }
  const result = {};
  for (const [key, hrefs] of Object.entries(input)) {
    const menu = MENU_CATALOG.find(group => group.key === key);
    if (!menu || !Array.isArray(hrefs)) {
      throw invalid('Choose a valid menu and a list of its pages.');
    }
    const allowed = new Set(menu.items.map(item => item.href));
    if (hrefs.length > allowed.size || new Set(hrefs).size !== hrefs.length
      || hrefs.some(href => typeof href !== 'string' || !allowed.has(href))) {
      throw invalid(`Only unique pages from ${menu.label} can be ordered.`);
    }
    if (hrefs.length) {result[key] = [...hrefs];}
  }
  return result;
}

export function orderMenuItems(items, order = []) {
  const ranks = new Map(order.map((href, index) => [href, index]));
  return items.map((item, index) => ({item, index})).sort((left, right) =>
    (ranks.get(left.item.href) ?? Number.MAX_SAFE_INTEGER)
    - (ranks.get(right.item.href) ?? Number.MAX_SAFE_INTEGER) || left.index - right.index
  ).map(row => row.item);
}

export function sanitizeStoredMenuOrders(input) {
  const result = {};
  for (const menu of MENU_CATALOG) {
    const hrefs = input?.[menu.key];
    if (!Array.isArray(hrefs)) {continue;}
    const allowed = new Set(menu.items.map(item => item.href));
    const retained = [...new Set(hrefs.filter(href => allowed.has(href)))];
    if (retained.length) {result[menu.key] = retained;}
  }
  return result;
}

export function moveMenuItem(items, from, to) {
  if (![from, to].every(index => Number.isInteger(index) && index >= 0 && index < items.length)) {
    throw invalid('Choose a position within the menu.');
  }
  const result = [...items];
  result.splice(to, 0, result.splice(from, 1)[0]);
  return result;
}
