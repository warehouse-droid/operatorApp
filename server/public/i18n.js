  function replaceVariables(text, variables = {}) {
    return Object.entries(variables).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value ?? "")),
      String(text || "")
    );
  }

  function language() {
    return localStorage.getItem(KEY) === ZH ? ZH : EN;
  }

  function t(key, fallback = "") {
    if (language() !== ZH) return fallback || key;
    return dictionary[key] || fallback || key;
  }

  function format(key, fallback = "", variables = {}) {
    return replaceVariables(t(key, fallback), variables);
  }

  function message(value) {
    const text = String(value || "");
    if (!text || language() !== ZH) return text;
    if (messageDictionary[text]) return messageDictionary[text];
    for (const [pattern, translate] of messageRules) {
      const match = text.match(pattern);
      if (match) return translate(match);
    }
    return text;
  }

  function toggleHtml() {
    const lang = language();
    return `
      <div class="language-toggle" role="group" aria-label="${t("lang.language", "Language")}">
        <button class="${lang === EN ? "active" : ""}" data-action="set-language" data-language="${EN}" type="button" title="${dictionary["lang.english"]}">EN</button>
        <button class="${lang === ZH ? "active" : ""}" data-action="set-language" data-language="${ZH}" type="button" title="${dictionary["lang.chinese"]}">简</button>
      </div>
    `;
  }

  function setLanguage(nextLanguage) {
    const normalized = nextLanguage === ZH ? ZH : EN;
    if (language() === normalized) return;
    localStorage.setItem(KEY, normalized);
    document.documentElement.lang = normalized;
    window.dispatchEvent(new CustomEvent("mbbs-language-changed", { detail: { language: normalized } }));
  }

  const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];
  const OPERATION_TIME_ZONE = "America/Toronto";

  function torontoDisplayDateParts(value, { preserveDateOnly = false } = {}) {
    if (!value) return null;
    if (preserveDateOnly && typeof value === "string") {
      const dateOnly = value.trim().match(/^(\d{4})-(\d{2})-(\d{2})$/);
      if (dateOnly) return { month: Number(dateOnly[2]), day: Number(dateOnly[3]) };
    }
    const date = value instanceof Date ? value : new Date(value);
    if (Number.isNaN(date.getTime())) return null;
    const parts = Object.fromEntries(new Intl.DateTimeFormat("en-CA", {
      timeZone: OPERATION_TIME_ZONE,
      month: "2-digit",
      day: "2-digit"
    }).formatToParts(date).map((part) => [part.type, part.value]));
    return { month: Number(parts.month), day: Number(parts.day) };
  }

  function localizedDisplayDate({ month, day }) {
    return language() === ZH
      ? `${month}月${day}日`
      : `${String(day).padStart(2, "0")}-${MONTHS[month - 1]}`;
  }

  function displayDate(value) {
    const parts = torontoDisplayDateParts(value, { preserveDateOnly: true });
    return parts ? localizedDisplayDate(parts) : "";
  }

  function displayDateTime(value) {
    if (!value) return "";
    const date = new Date(value);
    if (Number.isNaN(date.getTime())) return "";
    const localizedDate = localizedDisplayDate(torontoDisplayDateParts(date));
    const locale = language() === ZH ? "zh-CN" : "en-US";
    const localizedTime = date.toLocaleTimeString(locale, {
      timeZone: OPERATION_TIME_ZONE,
      hour: "2-digit",
      minute: "2-digit"
    });
    return `${localizedDate} ${localizedTime}`;
  }

