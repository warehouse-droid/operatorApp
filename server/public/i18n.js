  function language() {
    return localStorage.getItem(KEY) === ZH ? ZH : EN;
  }

  function t(key, fallback = "") {
    if (language() !== ZH) return fallback || key;
    return dictionary[key] || fallback || key;
  }

  function toggleHtml() {
    const lang = language();
    return `
      <div class="language-toggle" role="group" aria-label="Language">
        <button class="${lang === EN ? "active" : ""}" data-action="set-language" data-language="${EN}" type="button" title="${dictionary["lang.english"]}">EN</button>
        <button class="${lang === ZH ? "active" : ""}" data-action="set-language" data-language="${ZH}" type="button" title="${dictionary["lang.chinese"]}">简</button>
      </div>
    `;
  }

  function setLanguage(nextLanguage) {
    const normalized = nextLanguage === ZH ? ZH : EN;
    if (language() === normalized) return;
    localStorage.setItem(KEY, normalized);
    document.documentElement.lang = normalized;
    window.dispatchEvent(new CustomEvent("mbbs-language-changed", { detail: { language: normalized } }));
  }

  const MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

  function parseDisplayDate(value) {
    if (!value) return null;
    if (typeof value === "string") {
      const iso = value.match(/^(\d{4})-(\d{2})-(\d{2})/);
      if (iso) return new Date(Number(iso[1]), Number(iso[2]) - 1, Number(iso[3]));
    }
    const date = new Date(value);
    return Number.isNaN(date.getTime()) ? null : date;
  }

  function displayDate(value) {
    const date = parseDisplayDate(value);
    if (!date) return "";
    return `${String(date.getDate()).padStart(2, "0")}-${MONTHS[date.getMonth()]}`;
  }

  function displayDateTime(value) {
    if (!value) return "";
    const date = new Date(value);
    if (!date) return "";
    if (Number.isNaN(date.getTime())) return "";
    return `${displayDate(value)} ${date.toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" })}`;
  }

  document.documentElement.lang = language();

  document.addEventListener("click", (event) => {
    const button = event.target.closest("[data-action='set-language']");
    if (!button) return;
    setLanguage(button.dataset.language);
  });

  window.MBBS_I18N = {
    language,
    setLanguage,
    t,
    toggleHtml,
    displayDate,
    displayDateTime
  };
