  function text(value, variables = {}) {
    let translated = value;
    if (window.MBBS_I18N?.language() === 'zh-CN') {
      translated = chinese[value] || window.MBBS_I18N.message(value);
      const due = value.match(/^Report actual loads on or after (\d{4}-\d{2}-\d{2})\.$/);
      if (due) { translated = `请于 ${due[1]} 当天或之后填报实际车数。`; }
      const quantity = value.match(/^(.+): enter a whole number of loads from 0 to 1,000,000,000\.$/);
      if (quantity) { translated = `${chinese[quantity[1]] || quantity[1]}：请输入 0 至 1,000,000,000 之间的整数车数。`; }
      const failed = value.match(/^Request failed \((\d+)\)\.$/);
      if (failed) { translated = `请求失败（${failed[1]}）。`; }
    }
    return String(translated).replace(/\{(\w+)\}/g, (placeholder, key) => Object.hasOwn(variables, key) ? String(variables[key]) : placeholder);
  }
  function dateTime(value) {
    if (!value) { return '—'; }
    const date = new Date(value);
    if (!Number.isFinite(date.getTime())) { return '—'; }
    const language = window.MBBS_I18N?.language() === 'zh-CN' ? 'zh-CN' : 'en-CA';
    const formatted = new Intl.DateTimeFormat(language, {
      timeZone: 'America/Toronto', weekday: 'short', year: 'numeric', month: 'short', day: 'numeric',
      hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23', timeZoneName: 'short'
    }).format(date);
    return `${formatted} (${language === 'zh-CN' ? '多伦多' : 'Toronto'})`;
  }
  window.MBBSAggregateI18n = { text, dateTime };
